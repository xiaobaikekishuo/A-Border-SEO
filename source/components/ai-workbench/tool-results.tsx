"use client";

import Link from "next/link";
import { Copy } from "lucide-react";
import { useI18n } from "@/lib/i18n/client";
import type { Translator } from "@/lib/i18n/shared";
import type { WorkbenchResult } from "@/lib/ai-workbench/schema";
import type { SchemaReview } from "@/lib/ai-workbench/tools/schema";
import s from "./tool-panel.module.css";

/* Results of the structured tasks shown in the workbench: localization and structured data. */

function hreflangNote(code: string, t: Translator) {
  return (
    (
      {
        SAME_TAGS_ON_EVERY_VERSION: t(
          "Put the same set of tags on every language version, including the one pointing to itself.",
          "每个语言版本的页面都要放同一组标签，包括指向自己的那一条。",
        ),
        SOURCE_CODE_GUESSED: t(
          "The original page's language and region code is guessed from the site's market: check it.",
          "原文页面的语言地区代码是按站点市场推测的，请核对。",
        ),
        TARGET_URL_PLACEHOLDER: t(
          "Replace {localized-url} with the address of the localized page once it is published.",
          "本地化页面发布后，把 {localized-url} 换成它的网址。",
        ),
        REPLACED_EXISTING: t(
          "The page already had a version for this language and region; its address is replaced by the new one.",
          "原页面已有这个语言地区的版本，已改为指向新版本。",
        ),
        X_DEFAULT_SOURCE: t(
          "x-default points to the original page; point it to a language chooser if you have one.",
          "x-default 默认指向原文页面，如有语言选择页可改为指向它。",
        ),
        INVALID_EXISTING_SKIPPED: t(
          "Some existing alternate links of the page are invalid and were left out.",
          "原页面有部分无效的备用链接，已略去。",
        ),
      } as Record<string, string>
    )[code] ?? code
  );
}

export function LocalizationDetails({
  siteId,
  result,
  onCopy,
}: {
  siteId: string;
  result: Pick<WorkbenchResult, "localKeywords" | "hreflang">;
  onCopy: (text: string) => void;
}) {
  const { t } = useI18n();
  const plan = result.hreflang;
  return (
    <div className="mt-4 grid gap-4">
      {!!result.localKeywords?.length && (
        <div className={s.block}>
          <h4>{t("Local search terms", "当地搜索用词")}</h4>
          <p className={s.url}>
            {t(
              "Suggestions from the model, not measured demand. Check their search volume for the target market in keyword research before relying on them.",
              "这些是模型的建议，不是实测数据。使用前请在关键词研究里核实目标市场的搜索量。",
            )}{" "}
            <Link className="text-link" href={`/sites/${encodeURIComponent(siteId)}/keyword-research`}>
              {t("Keyword research →", "关键词研究 →")}
            </Link>
          </p>
          <div className={s.tableWrap}>
            <table className={s.table}>
              <thead>
                <tr>
                  <th>{t("Term", "用词")}</th>
                  <th>{t("Intent", "意图")}</th>
                  <th>{t("Where", "位置")}</th>
                  <th>{t("Note", "说明")}</th>
                </tr>
              </thead>
              <tbody>
                {result.localKeywords.map(item => (
                  <tr key={item.keyword}>
                    <td>
                      <strong>{item.keyword}</strong>
                    </td>
                    <td>{item.intent}</td>
                    <td>{item.use}</td>
                    <td>{item.note}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}
      {plan ? (
        <div className={s.block}>
          <h4>
            hreflang <span className={s.badge}>{plan.code}</span>
          </h4>
          <p className={s.url}>
            {t(
              "Generated by the program from the page's alternates in the latest crawl, not by the model.",
              "由程序根据最近抓取到的原页面备用链接生成，不是模型写的。",
            )}
          </p>
          <pre className={s.code}>{plan.html}</pre>
          <div>
            <button type="button" className={s.copy} onClick={() => onCopy(plan.html)}>
              <Copy size={12} />
              {t("Copy tags", "复制标签")}
            </button>
          </div>
          <ul className={s.list}>
            {plan.notes.map(code => (
              <li key={code}>{hreflangNote(code, t)}</li>
            ))}
          </ul>
        </div>
      ) : (
        <p className={s.url}>
          {t(
            "No hreflang tags: the article was pasted, so its page address is unknown. Choose a crawled page to get them.",
            "没有 hreflang 标签：原文是粘贴的，不知道原页面网址。选择已抓取的页面才会生成。",
          )}
        </p>
      )}
    </div>
  );
}

function needText(reason: string, t: Translator) {
  return (
    (
      {
        NOT_ON_PAGE: t("not on the page: add it if true", "页面上没有，如属实请补充"),
        IMAGE_UNKNOWN: t("needs the image address", "需要图片网址"),
        DATE_NOT_ON_PAGE: t("date not shown on the page", "页面上没有这个日期"),
        REQUIRED: t("required", "必填"),
        PRODUCT_NEEDS_OFFER: t("a product result needs a price, a review or a rating", "要显示产品结果，需要价格、评价或评分"),
      } as Record<string, string>
    )[reason] ?? reason
  );
}
function removedText(reason: SchemaReview["removed"][number]["reason"], t: Translator) {
  return {
    NOT_ON_PAGE: t("value not found on the page", "页面上找不到这个值"),
    URL_NOT_ALLOWED: t("not an address of this page or site", "不是本页或本站的网址"),
    IMAGE_UNKNOWN: t("image address unknown", "图片网址未知"),
    DATE_NOT_ON_PAGE: t("date not on the page", "日期与页面不符"),
    TEXT_CORRECTED: t("replaced by the page's own text", "改用页面上的文字"),
    INCOMPLETE: t("incomplete, removed whole", "缺少必要字段，整项移除"),
    NOT_ALLOWED: t("nested too deep", "层级过深"),
  }[reason];
}
function errorText(code: string | null, t: Translator) {
  return (
    (
      {
        INVALID_JSON: t("The code is not valid JSON.", "代码不是有效的 JSON。"),
        NOT_AN_OBJECT: t("The code is not one JSON-LD object.", "代码不是一个 JSON-LD 对象。"),
        GRAPH_NOT_SUPPORTED: t("Several entities in one @graph are not checked here.", "这里不检查 @graph 多实体写法。"),
        TYPE_MISMATCH: t("The @type differs from the type asked for.", "@type 与要求的类型不一致。"),
        EMPTY_AFTER_CHECKS: t("Nothing the page supports was left.", "去掉页面不支持的内容后已无剩余。"),
      } as Record<string, string>
    )[code ?? ""] ??
    code ??
    ""
  );
}

export function SchemaReviewList({ reviews, onCopy }: { reviews: SchemaReview[]; onCopy: (text: string) => void }) {
  const { t } = useI18n();
  const label = {
    READY: [t("Ready to use", "可以使用"), s.good],
    NEEDS_INPUT: [t("Needs input", "需要补充"), s.warn],
    REJECTED: [t("Did not pass", "未通过检查"), s.bad],
  } as const;
  return (
    <div className="mt-4 grid gap-4">
      <p className={s.url}>
        {t(
          "Checked by the program: values the page does not show were removed and listed. Test the code with Google's Rich Results Test before publishing.",
          "已由程序检查：页面上没有的值已去掉并列出。发布前请用 Google 富媒体搜索结果测试工具检查。",
        )}
      </p>
      {reviews.map(review => (
        <div key={review.type} className={s.block}>
          <h4>
            {review.type} <span className={`${s.badge} ${label[review.status][1]}`}>{label[review.status][0]}</span>
          </h4>
          {review.status === "REJECTED" ? (
            <p className={s.url}>{errorText(review.error, t)}</p>
          ) : (
            <>
              <pre className={s.code}>{review.html}</pre>
              <div>
                <button type="button" className={s.copy} onClick={() => onCopy(review.html)}>
                  <Copy size={12} />
                  {t("Copy code", "复制代码")}
                </button>
              </div>
            </>
          )}
          {!!review.needs.length && (
            <>
              <strong className="text-sm">{t("For you to add", "需要你补充")}</strong>
              <ul className={s.list}>
                {review.needs.map(item => (
                  <li key={item.property}>
                    <code>{item.property}</code>: {needText(item.reason, t)}
                  </li>
                ))}
              </ul>
            </>
          )}
          {!!review.removed.length && (
            <details>
              <summary className={s.url}>{t(`Removed (${review.removed.length})`, `已移除（${review.removed.length}）`)}</summary>
              <ul className={s.list}>
                {review.removed.map((item, i) => (
                  <li key={i}>
                    <code>{item.path}</code>: {removedText(item.reason, t)}
                  </li>
                ))}
              </ul>
            </details>
          )}
        </div>
      ))}
    </div>
  );
}
