export interface UiTranslator {
  (source: string, values?: Record<string, string | number>): string;
  locale?: Locale;
}

function interpolate(source: string, values?: Record<string, string | number>): string {
  return source.replace(/\{(\d+)\}/g, (match, key) => values?.[key] === undefined ? match : String(values[key]));
}

export const identityUiText: UiTranslator = (source, values) => interpolate(source, values);
identityUiText.locale = "en";

export function useUiText(): UiTranslator {
  const { locale } = useI18n();
  return useMemo(() => {
    const ui: UiTranslator = (source, values) => {
      const trimmed = source.trim();
      const translated = locale === "zh" ? messages[source] ?? (messages[trimmed] ? source.replace(trimmed, messages[trimmed]) : source) : source;
      return interpolate(translated, values);
    };
    ui.locale = locale;
    return ui;
  }, [locale]);
}
